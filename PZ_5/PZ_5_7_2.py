#Описать функцию AddRightDigit(D, K), добавляющую к целому положительному числу K справа цифру D (D — входной параметр целого типа, лежащий в диапазоне 0-9, K — параметр целого типа, являющийся одновременно входным и выходным). С помощью этой функции последовательно добавить к данному числу K справа данные цифры D1 и D2, выводя результат каждого добавления.
def AddRightDigit(D, K):
    return K * 10 + D
while True:
    try:
        K = int(input("Введите целое положительное число K: "))
        if K <= 0:
            print("Число K должно быть положительным! Попробуйте снова.")
            continue
        D1 = int(input("Введите цифру D1 (от 0 до 9): "))
        if not (0 <= D1 <= 9):
            print("Цифра D1 должна быть в диапазоне от 0 до 9!")
            continue
        D2 = int(input("Введите цифру D2 (от 0 до 9): "))
        if not (0 <= D2 <= 9):
            print("Цифра D2 должна быть в диапазоне от 0 до 9!")
            continue
        K = AddRightDigit(D1, K)
        print(f"После добавления D1 ({D1}), результат: {K}")
        K = AddRightDigit(D2, K)
        print(f"После добавления D2 ({D2}), результат: {K}")
        break
    except ValueError:
        print("Ошибка ввода! Пожалуйста, вводите только целые числа.")
