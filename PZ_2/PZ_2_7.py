# Дана масса M в килограммах. Используя операцию деления нацело, найти количество полных тонн в ней (1 тонна = 1000 кг).
try:
    # ввод массы и преобразование в целое число
    mass = int(input("Введите массу в килограммах: "))
    # целочисленное деление на 1000 для получения полных тонн
    tons = mass // 1000
    # вывод результата
    print(f"Количество полных тонн: {tons}")
except ValueError:
    # обработка ошибки при вводе нечислового значения
     print("Ошибка")
