# Единицы массы: 1 — килограмм, 2 — миллиграмм, 3 — грамм, 4 — тонна, 5 — центнер. Дан номер единицы массы (1-5) и масса тела в этих единицах (вещественное число).Найти массу тела в килограммах.
# Ввод и валидация номера единицы массы (целое число от 1 до 5)
unit = input("Введите номер единицы массы (1-5): ")
while type(unit) != int:
    try:
        unit = int(unit)
        if unit < 1 or unit > 5:
            print("Ошибка! Номер должен быть в диапазоне от 1 до 5.")
            unit = input("Введите номер единицы массы (1-5): ")
            # Сбрасываем тип, чтобы цикл продолжился, если число вне диапазона
            continue  
    except ValueError:
        print("Неправильно ввели! Ожидается целое число.")
        unit = input("Введите номер единицы массы (1-5): ")

# Ввод и валидация массы тела (вещественное число)
mass = input("Введите массу тела в выбранных единицах: ")
while type(mass) != float:
    try:
        mass = float(mass)
        if mass < 0:
            print("Предупреждение: масса не должна быть отрицательной!")
    except ValueError:
        print("Неправильно ввели! Ожидается вещественное или целое число.")
        mass = input("Введите массу тела в выбранных единицах: ")

# Структура ветвления для перевода массы в килограммы
if unit == 1:
    # килограмм
    result = mass          
    unit_name = "кг"
elif unit == 2:
    # миллиграмм (0.000001 кг)
    result = mass * 1e-6   
    unit_name = "мг"
elif unit == 3:
    # грамм (0.001 кг)
    result = mass * 0.001  
    unit_name = "г"
elif unit == 4:
    # тонна (1000 кг)
    result = mass * 1000.0 
    unit_name = "т"
elif unit == 5:
    # центнер (100 кг)
    result = mass * 100.0  
    unit_name = "ц"

print(f"Исходная масса: {mass} {unit_name}")
print(f"Масса тела в килограммах = {result} кг")
