#Дана непустая строка. Вывести коды ее первого и последнего символа.
s = input("введите непустую строку: ")
if len(s) > 0:
    a = ord(s[0])
    b = ord(s[-1])
    print("исходная строка:", s)
    print("код первого символа:", a)
    print("код последнего символа:", b)
else:
    print("ошибка введена пустая строка.")
